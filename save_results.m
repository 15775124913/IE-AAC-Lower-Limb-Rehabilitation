function save_results(params, t_all, ...
    q_teach, q_fixed, q_zhang, q_cao, q_adaptive, ...
    dq_teach, dq_fixed, dq_zhang, dq_cao, dq_adaptive, ...
    ddq_teach, ddq_fixed, ddq_zhang, ddq_cao, ddq_adaptive, ...
    heel_teach, heel_fixed, heel_zhang, heel_cao, heel_adaptive, ...
    toe_teach, toe_fixed, toe_zhang, toe_cao, toe_adaptive, ...
    ctrl_params_fixed, ctrl_params_zhang, ctrl_params_cao, ctrl_params_adp, ...
    metrics_fixed, metrics_zhang, metrics_cao, metrics_adaptive, ...
    e_fb_raw_fixed, e_fb_used_fixed, ...
    e_fb_raw_zhang, e_fb_used_zhang, ...
    e_fb_raw_cao, e_fb_used_cao, ...
    e_fb_raw_adp, e_fb_used_adp, ...
    fb_nominal_adp, fb_true_adp, fb_real_adp, ...
    interaction_diag_fixed, interaction_diag_zhang, interaction_diag_cao, interaction_diag_adp, ...
    T_nominal_primary, T_nominal_diagnostic)
%SAVE_RESULTS Save traceable four-controller nominal results.
% Controllers: Fixed / Zhang-2018 VA / Cao-2024-derived VA / Proposed IE-AAC.

    results_dir = 'results';
    if ~exist(results_dir, 'dir'), mkdir(results_dir); end

    timestamp = char(params.config_date);
    subfolder = fullfile(results_dir, timestamp);
    if ~exist(subfolder, 'dir'), mkdir(subfolder); end
    fprintf('📁 四控制器结果保存至：%s\n', subfolder);

    %% ================= controller parameter sequences =================
    Ba_fixed = ctrl_params_fixed.Ba; Ka_fixed = ctrl_params_fixed.Ka; Ga_fixed = ctrl_params_fixed.Ga;
    quiet_zone_flag_fixed = ctrl_params_fixed.quiet_zone_flag;
    Ba_zhang = ctrl_params_zhang.Ba; Ka_zhang = ctrl_params_zhang.Ka; Ga_zhang = ctrl_params_zhang.Ga;
    quiet_zone_flag_zhang = ctrl_params_zhang.quiet_zone_flag;
    Ba_cao = ctrl_params_cao.Ba; Ka_cao = ctrl_params_cao.Ka; Ga_cao = ctrl_params_cao.Ga;
    quiet_zone_flag_cao = ctrl_params_cao.quiet_zone_flag;
    Ba_adp = ctrl_params_adp.Ba; Ka_adp = ctrl_params_adp.Ka; Ga_adp = ctrl_params_adp.Ga;
    quiet_zone_flag_adp = ctrl_params_adp.quiet_zone_flag;

    %% ================= 1. Full MAT =================
    mat_filename = fullfile(subfolder, ['sim_full_four_controller_' timestamp '.mat']);
    save(mat_filename, ...
        'params','t_all', ...
        'q_teach','q_fixed','q_zhang','q_cao','q_adaptive', ...
        'dq_teach','dq_fixed','dq_zhang','dq_cao','dq_adaptive', ...
        'ddq_teach','ddq_fixed','ddq_zhang','ddq_cao','ddq_adaptive', ...
        'heel_teach','heel_fixed','heel_zhang','heel_cao','heel_adaptive', ...
        'toe_teach','toe_fixed','toe_zhang','toe_cao','toe_adaptive', ...
        'Ba_fixed','Ka_fixed','Ga_fixed','quiet_zone_flag_fixed', ...
        'Ba_zhang','Ka_zhang','Ga_zhang','quiet_zone_flag_zhang', ...
        'Ba_cao','Ka_cao','Ga_cao','quiet_zone_flag_cao', ...
        'Ba_adp','Ka_adp','Ga_adp','quiet_zone_flag_adp', ...
        'metrics_fixed','metrics_zhang','metrics_cao','metrics_adaptive', ...
        'e_fb_raw_fixed','e_fb_used_fixed', ...
        'e_fb_raw_zhang','e_fb_used_zhang', ...
        'e_fb_raw_cao','e_fb_used_cao', ...
        'e_fb_raw_adp','e_fb_used_adp', ...
        'fb_nominal_adp','fb_true_adp','fb_real_adp', ...
        'interaction_diag_fixed','interaction_diag_zhang','interaction_diag_cao','interaction_diag_adp', ...
        'T_nominal_primary','T_nominal_diagnostic','-v7.3');
    fprintf('✅ 完整四控制器 MAT 已保存：%s\n', mat_filename);

    %% ================= 2. Joint state CSV =================
    joint_table = array2table([t_all, ...
        q_teach*180/pi, q_fixed*180/pi, q_zhang*180/pi, q_cao*180/pi, q_adaptive*180/pi, ...
        dq_teach*180/pi, dq_fixed*180/pi, dq_zhang*180/pi, dq_cao*180/pi, dq_adaptive*180/pi, ...
        ddq_teach*180/pi, ddq_fixed*180/pi, ddq_zhang*180/pi, ddq_cao*180/pi, ddq_adaptive*180/pi], ...
        'VariableNames', {'Time_s', ...
        'q_hip_ref','q_knee_ref','q_ankle_ref', ...
        'q_hip_fixed','q_knee_fixed','q_ankle_fixed', ...
        'q_hip_zhang2018','q_knee_zhang2018','q_ankle_zhang2018', ...
        'q_hip_cao2024','q_knee_cao2024','q_ankle_cao2024', ...
        'q_hip_proposed','q_knee_proposed','q_ankle_proposed', ...
        'dq_hip_ref','dq_knee_ref','dq_ankle_ref', ...
        'dq_hip_fixed','dq_knee_fixed','dq_ankle_fixed', ...
        'dq_hip_zhang2018','dq_knee_zhang2018','dq_ankle_zhang2018', ...
        'dq_hip_cao2024','dq_knee_cao2024','dq_ankle_cao2024', ...
        'dq_hip_proposed','dq_knee_proposed','dq_ankle_proposed', ...
        'ddq_hip_ref','ddq_knee_ref','ddq_ankle_ref', ...
        'ddq_hip_fixed','ddq_knee_fixed','ddq_ankle_fixed', ...
        'ddq_hip_zhang2018','ddq_knee_zhang2018','ddq_ankle_zhang2018', ...
        'ddq_hip_cao2024','ddq_knee_cao2024','ddq_ankle_cao2024', ...
        'ddq_hip_proposed','ddq_knee_proposed','ddq_ankle_proposed'});
    writetable(joint_table, fullfile(subfolder, ['joints_four_controller_' timestamp '.csv']));

    %% ================= 3. Foot trajectories =================
    foot_table = array2table([t_all, ...
        heel_teach, heel_fixed, heel_zhang, heel_cao, heel_adaptive, ...
        toe_teach, toe_fixed, toe_zhang, toe_cao, toe_adaptive], ...
        'VariableNames', {'Time_s', ...
        'HEEL_ref_x','HEEL_ref_y','HEEL_fixed_x','HEEL_fixed_y', ...
        'HEEL_zhang2018_x','HEEL_zhang2018_y','HEEL_cao2024_x','HEEL_cao2024_y','HEEL_proposed_x','HEEL_proposed_y', ...
        'TOE_ref_x','TOE_ref_y','TOE_fixed_x','TOE_fixed_y', ...
        'TOE_zhang2018_x','TOE_zhang2018_y','TOE_cao2024_x','TOE_cao2024_y','TOE_proposed_x','TOE_proposed_y'});
    writetable(foot_table, fullfile(subfolder, ['foot_trajectories_four_controller_' timestamp '.csv']));

    %% ================= 4. Admittance parameter histories =================
    param_table = array2table([t_all, ...
        Ba_fixed, Ka_fixed, Ga_fixed, ...
        Ba_zhang, Ka_zhang, Ga_zhang, ...
        Ba_cao, Ka_cao, Ga_cao, ...
        Ba_adp, Ka_adp, Ga_adp], ...
        'VariableNames', {'Time_s', ...
        'Ba_hip_fixed','Ba_knee_fixed','Ba_ankle_fixed', ...
        'Ka_hip_fixed','Ka_knee_fixed','Ka_ankle_fixed', ...
        'Ga_hip_fixed','Ga_knee_fixed','Ga_ankle_fixed', ...
        'Ba_hip_zhang2018','Ba_knee_zhang2018','Ba_ankle_zhang2018', ...
        'Ka_hip_zhang2018','Ka_knee_zhang2018','Ka_ankle_zhang2018', ...
        'Ga_hip_zhang2018','Ga_knee_zhang2018','Ga_ankle_zhang2018', ...
        'Ba_hip_cao2024','Ba_knee_cao2024','Ba_ankle_cao2024', ...
        'Ka_hip_cao2024','Ka_knee_cao2024','Ka_ankle_cao2024', ...
        'Ga_hip_cao2024','Ga_knee_cao2024','Ga_ankle_cao2024', ...
        'Ba_hip_proposed','Ba_knee_proposed','Ba_ankle_proposed', ...
        'Ka_hip_proposed','Ka_knee_proposed','Ka_ankle_proposed', ...
        'Ga_hip_proposed','Ga_knee_proposed','Ga_ankle_proposed'});
    writetable(param_table, fullfile(subfolder, ['admittance_four_controller_' timestamp '.csv']));

    %% ================= 5. Interaction signals =================
    N = length(t_all);
    if isempty(fb_nominal_adp), fb_nominal_adp = zeros(N,3); end
    if isempty(fb_true_adp), fb_true_adp = zeros(N,3); end
    if isempty(fb_real_adp), fb_real_adp = zeros(N,3); end

    interaction_table = array2table([t_all, ...
        fb_nominal_adp, fb_true_adp, fb_real_adp, ...
        e_fb_raw_fixed, e_fb_raw_zhang, e_fb_raw_cao, e_fb_raw_adp, ...
        e_fb_used_fixed, e_fb_used_zhang, e_fb_used_cao, e_fb_used_adp], ...
        'VariableNames', {'Time_s', ...
        'fb_nominal_hip','fb_nominal_knee','fb_nominal_ankle', ...
        'fb_true_hip','fb_true_knee','fb_true_ankle', ...
        'fb_real_hip','fb_real_knee','fb_real_ankle', ...
        'raw_fixed_hip','raw_fixed_knee','raw_fixed_ankle', ...
        'raw_zhang2018_hip','raw_zhang2018_knee','raw_zhang2018_ankle', ...
        'raw_cao2024_hip','raw_cao2024_knee','raw_cao2024_ankle', ...
        'raw_proposed_hip','raw_proposed_knee','raw_proposed_ankle', ...
        'used_fixed_hip','used_fixed_knee','used_fixed_ankle', ...
        'used_zhang2018_hip','used_zhang2018_knee','used_zhang2018_ankle', ...
        'used_cao2024_hip','used_cao2024_knee','used_cao2024_ankle', ...
        'used_proposed_hip','used_proposed_knee','used_proposed_ankle'});
    writetable(interaction_table, fullfile(subfolder, ['interaction_four_controller_' timestamp '.csv']));

    %% ================= 6. Primary metrics + supervisory diagnostics =================
    writetable(T_nominal_primary, fullfile(subfolder, ['nominal_primary_metrics_' timestamp '.csv']));
    writetable(T_nominal_diagnostic, fullfile(subfolder, ['nominal_supervisory_diagnostics_' timestamp '.csv']));
    summary_metrics = struct('fixed',metrics_fixed, ...
                             'zhang2018',metrics_zhang, ...
                             'cao2024',metrics_cao, ...
                             'adaptive',metrics_adaptive);
    save(fullfile(subfolder, ['metrics_summary_four_controller_' timestamp '.mat']), ...
         'summary_metrics','T_nominal_primary','T_nominal_diagnostic');

    config_summary = struct();
    config_summary.date = timestamp;
    config_summary.dt = params.dt;
    config_summary.loop_num = params.loop_num;
    config_summary.total_time = t_all(end);
    config_summary.version = params.version;
    config_summary.literature_zhang2018 = params.literature_zhang2018;
    config_summary.literature_cao2024 = params.literature_cao2024;
    save(fullfile(subfolder, ['config_summary_' timestamp '.mat']), 'config_summary');

    fprintf('✅ CSV/MAT 导出完成：Fixed / Zhang-2018 / Cao-2024-derived / Proposed IE-AAC。\n');
end
